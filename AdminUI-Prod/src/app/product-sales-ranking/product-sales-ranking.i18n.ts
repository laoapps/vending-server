export const I18N: Record<Lang, Record<string, string>> = { en, lo };

export function translate(lang: Lang, key: I18nKey | string, params?: Record<string, any>): string {
  const dict = I18N[lang] || I18N.en;
  const n = params?.['n'];
  const pick = (d: Record<string, string>) => (n === 1 && d[key + '_one']) || d[key];
  let text = pick(dict) ?? pick(I18N.en) ?? String(key);
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? '') + '');
  }
  return text;
}
